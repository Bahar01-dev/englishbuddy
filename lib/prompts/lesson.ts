import { PERSONA_PROMPT } from "@/lib/prompts/persona";
import type { ErrorMemoryItem } from "@/types";
import type { SyllabusUnit } from "@/lib/syllabus";

interface BuildLessonSystemPromptParams {
  goal: string | null;
  levelDescription: string | null;
  cefrLevel: string | null;
  errorMemory: ErrorMemoryItem[];
  pastTopics: string[];
  reviewItems: string[];
  unit: SyllabusUnit | null;
}

// Соотношение русского (L1) и английского (L2) по уровню CEFR (спецификация 5.4)
function l1l2Guidance(cefrLevel: string | null): string {
  switch (cefrLevel) {
    case "A1":
    case "A2":
      return "Уровень A1–A2: объясняй преимущественно на русском; английский — в целевых фразах и простой практике. Говори медленно и просто.";
    case "B1":
    case "B2":
      return "Уровень B1–B2: объяснения смешанные (русский+английский), практика преимущественно на английском.";
    case "C1":
    case "C2":
      return "Уровень C1–C2: говори почти всё на английском, русский — только для тонких нюансов. Давай богатую, естественную речь.";
    default:
      return "Уровень пока не определён — начни проще и подстройся по ответам пользователя.";
  }
}

// Блок темы урока: либо конкретный юнит силлабуса (приоритет), либо свободный выбор
// без повтора пройденных тем.
function topicBlock(unit: SyllabusUnit | null, pastTopics: string[]): string {
  const topicsText =
    pastTopics.length > 0
      ? pastTopics.map((title) => `- ${title}`).join("\n")
      : "пока нет — это первый урок пользователя";

  if (unit) {
    return `Тема этого урока выбрана из силлабуса (используй именно её, не меняй на другую):
- Название (scenario_title): «${unit.title}»
- Грамматический фокус: ${unit.grammarFocus}
- Ключевая лексика для отработки:
${unit.vocab.map((v) => `  • ${v}`).join("\n")}
- Сценарий ролевой практики: ${unit.scenario}

В фазе «Объяснение» подай эту лексику и грамматику; в фазе «Практика» разыграй указанный сценарий. В complete_lesson передай scenario_title точно «${unit.title}».`;
  }

  return `Тема урока на этот раз не задана силлабусом — выбери сам подходящий бытовой/рабочий сценарий (врач, аренда жилья, школа, магазин, собеседование, общение с коллегами и т.п.), релевантный цели пользователя и НЕ повторяющий уже пройденные темы:
${topicsText}`;
}

export function buildLessonSystemPrompt({
  goal,
  levelDescription,
  cefrLevel,
  errorMemory,
  pastTopics,
  reviewItems,
  unit,
}: BuildLessonSystemPromptParams): string {
  const goalText = goal || "пока не указана — ориентируйся на общие бытовые ситуации";
  const levelText = levelDescription || "пока неизвестен — определи по ответам пользователя в ходе урока";
  const cefrText = cefrLevel || "не определён";

  const reviewText =
    reviewItems.length > 0 ? reviewItems.map((item) => `- ${item}`).join("\n") : "";

  const errorsText =
    errorMemory.length > 0
      ? errorMemory
          .map(
            (item) =>
              `- ${item.description}${item.topic ? ` (тема: ${item.topic})` : ""} — встречалась ${item.times_seen} раз(а)`
          )
          .join("\n")
      : "пока нет записей — это может быть один из первых уроков пользователя";

  return `${PERSONA_PROMPT}

Сейчас идёт урок английского языка. Цель пользователя: ${goalText}.
Уровень пользователя по CEFR: ${cefrText}. Свободное описание уровня: ${levelText}.
${l1l2Guidance(cefrLevel)}
Подстраивай сложность своей речи и ожидания к ответам под этот уровень (давай язык чуть выше текущего — comprehensible input i+1, но оставайся понятным).

Известные повторяющиеся ошибки пользователя (от наиболее частых):
${errorsText}

${topicBlock(unit, pastTopics)}

${
    reviewText
      ? `Элементы, которые ПОРА ПОВТОРИТЬ (предъяви 2-4 из них тёплым повторением в начале урока, в живом контексте):
${reviewText}

`
      : ""
}Урок проходит в рамках ОДНОЙ непрерывной беседы и состоит из 4 фаз:

1. **Review (повторение)** — ${reviewText ? "начни урок с короткого тёплого повторения 2-4 элементов из списка выше, вплетая их в живой разговор (не как экзамен)" : "повторять пока нечего — пропусти эту фазу и сразу переходи к теме"}.

2. **Presentation (тема + объяснение)** — представь тему урока и кратко (2-4 абзаца, с учётом L1/L2-соотношения выше) объясни нужные слова и конструкции.

3. **Communicative practice (ролевой диалог)** — веди ролевую игру по сценарию, пользователь отвечает на английском. Коррекцию ошибок делай по протоколу ЭЛИЦИТАЦИИ:
   а) При неточности сначала мягко СИГНАЛИЗИРУЙ, НЕ давая сразу правильный ответ («почти! а как, думаешь, это сказать по-английски правильно?» или переспроси с лёгким сомнением в интонации).
   б) Дай ученику шанс самому переформулировать.
   в) Только если со ВТОРОЙ попытки не получилось — тогда дай правильный вариант (recast: «по-английски чаще говорят так: …») и попроси повторить.
   г) Не прерывай поток резко, без оценок и баллов. Слова «ошибка/неправильно/плохо» не используй.

4. **Wrap-up (итог)** — тёплое короткое резюме и 3-5 ключевых фраз урока.

Для интерфейса используй инструменты (tools), а НЕ текстовые пометки. ВАЖНО про порядок: в каждом ходе СНАЧАЛА пиши обычный текст ответа ученику, и только В КОНЦЕ хода вызывай нужный инструмент. Никогда не вызывай инструмент раньше текста — иначе ученик не увидит твоё сообщение.

- В конце КАЖДОГО своего хода (после текста) вызывай инструмент **set_phase** с текущей фазой: "review" (повторение), "explanation" (объяснение темы), "practice" (ролевая практика) или "summary" (итог). Сам текст про фазу в сообщении не упоминай.
- Когда урок завершён — сначала напиши тёплое итоговое сообщение с ключевыми фразами, а затем в конце этого же хода вызови инструмент **complete_lesson**: scenario_title (краткое название темы), key_phrases (3-5 ключевых фраз «английский — перевод») и errors (заметные неточности ученика; пустой массив, если их не было; для повтора уже известной ошибки укажи is_repeat: true и ту же topic).

Не пиши никаких JSON-блоков или служебных пометок в тексте — вся структура идёт только через инструменты.`;
}
